# =============================================================================
#  AMMSIS — lib/help.sh
#  Function to show help and usage
# =============================================================================

show_help() {
    print_banner
    echo -e "${CLR_BOLD}UTILIZZO:${CLR_RESET}"
    echo "  ./ammsis.sh                   Wizard interattivo (setup completo)"
    echo "  ./ammsis.sh --maketar [opts]  Modalità consegna (raccolta file)"
    echo "  ./ammsis.sh --help            Mostra questo aiuto"
    echo ""
    echo -e "${CLR_BOLD}MODALITÀ SETUP (wizard interattivo):${CLR_RESET}"
    echo "  Il wizard guida l'utente nella configurazione della topologia di rete,"
    echo "  chiedendo per ogni tipo di nodo (router, client, server):"
    echo "    - Numero di istanze"
    echo "    - Subnet della rete (CIDR prefix 1-32)"
    echo "    - Modalità rete: DHCP o IP statico"
    echo "    - Per DHCP: rete, range IP, rotta opzionale"
    echo "    - Per statico: IP e segmento intnet per ogni interfaccia"
    echo ""
    echo -e "${CLR_BOLD}NOMI DELLE VM:${CLR_RESET}"
    echo "  I nomi delle macchine virtuali seguono la convenzione:"
    echo "    - WKS1, WKS2, ...  per i client (workstation)"
    echo "    - ROU1, ROU2, ...  per i router"
    echo "    - SRV1, SRV2, ...  per i server"
    echo ""
    echo -e "${CLR_BOLD}CONNETTIVITÀ DI RETE:${CLR_RESET}"
    echo "  Per connettere macchine diverse sulla stessa rete, assegna lo stesso"
    echo "  nome di segmento intnet alle interfacce che devono comunicare."
    echo "  Esempio:"
    echo "    ROU1 eth1 → segmento 'NET1'  + WKS1 eth1 → segmento 'NET1'"
    echo "    ROU1 eth2 → segmento 'NET2'  + SRV1 eth1 → segmento 'NET2'"
    echo ""
    echo -e "${CLR_BOLD}DHCP:${CLR_RESET}"
    echo "  I client e i server possono essere configurati con DHCP."
    echo "  I router fungono da server DHCP (dnsmasq); con più router sulla stessa"
    echo "  rete, ciascun router può gestire un proprio pool DHCP indipendente."
    echo "  Lo script configura automaticamente:"
    echo "    - dnsmasq.conf con range e rotte statiche (per-router se multi-router)"
    echo "    - File di interfaccia DHCP per i client/server"
    echo ""
    echo -e "${CLR_BOLD}SSH PASSWORDLESS:${CLR_RESET}"
    echo "  Se sono presenti >= 2 client o >= 2 server, lo script può configurare"
    echo "  l'accesso SSH con chiavi (senza password) tra nodi dello stesso tipo."
    echo "  Le chiavi sono separate: mai accesso cross tra client e server."
    echo ""
    echo -e "${CLR_BOLD}PROVISIONING:${CLR_RESET}"
    echo "  Ogni VM è configurata con provisioning Ansible (site.yml)."
    echo "  Lo script copia automaticamente i componenti dalla cartella"
    echo "  componenti/ nella struttura roles/ e li configura con i dati di rete."
    echo ""
    echo -e "${CLR_BOLD}MODALITÀ CONSEGNA (--maketar):${CLR_RESET}"
    echo "  Opzioni passate a maketar.sh:"
    echo "    -h, --help           Mostra l'aiuto di maketar"
    echo "    -d, --dry-run        Simula senza scaricare file"
    echo "    -v, --verbose        Debug avanzato"
    echo "    -n, --name NOME      Nome archivio personalizzato"
    echo ""
    echo -e "${CLR_BOLD}PASSI ESEGUITI DAL SETUP:${CLR_RESET}"
    echo "  1. Raccolta interattiva della topologia di rete"
    echo "  2. Generazione del Vagrantfile (con provisioning Ansible)"
    echo "  3. Copia e configurazione dei componenti Ansible (roles/ + site.yml)"
    echo "  4. Avvio delle macchine virtuali (vagrant up)"
    echo "  5. Generazione dello script di consegna (maketar.sh)"
    echo ""
    echo -e "${CLR_DIM}AMMSIS v${AMMSIS_VERSION}${CLR_RESET}"
}
